def main() -> None:
    lines = [
        "# NeoTeletext's stroke font for NAPLPS: the primary set, drawn for NeoTeletext.",
        "# Written by scripts/make_font.py, which holds each glyph's strokes; edit that, not this.",
        "[primary]",
    ]
    for code in range(0x21, 0x7F):
        strokes = GLYPHS[chr(code)]
        segments = []
        for stroke in strokes:
            points = stroke if len(stroke) > 1 else [stroke[0], stroke[0]]
            for (x1, y1), (x2, y2) in zip(points, points[1:]):
                assert 0 <= min(x1, x2) and max(x1, x2) < GRID_WIDTH and 0 <= min(y1, y2) and max(y1, y2) < GRID_HEIGHT, chr(code)
                segments.append(f"{x1},{y1},{x2},{y2}")
        assert 0 < len(segments) <= MAX_SEGMENTS, chr(code)
        lines.append(f"{code:02x} {METRICS} " + " ".join(segments))
    pathlib.Path("fonts/neoteletext.strokes").write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
