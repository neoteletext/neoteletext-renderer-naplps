def hill(p, lift):
    def polygon(points, ink):
        p.poly([(x, y-lift) for x, y in points], ink)

    def line(points, ink, width):
        p.line([(x, y-lift) for x, y in points], ink, width)

    polygon([(159, 315), (201, 249), (269, 220), (319, 223), (363, 188),
            (430, 189), (497, 243), (553, 252), (573, 293), (522, 322),
            (361, 349), (236, 342)], 6)
    polygon([(235, 256), (270, 232), (320, 236), (369, 202), (413, 203),
            (467, 232), (428, 224), (374, 221), (328, 253), (283, 245)], 7)
    # Exposed strata curve around the body of the moving hill.
    polygon([(183, 305), (229, 278), (273, 269), (323, 280), (380, 249),
            (433, 242), (478, 252), (431, 251), (382, 265), (325, 294),
            (270, 282), (229, 287)], 2)
    line([(286, 312), (331, 315), (385, 293), (451, 281), (495, 287)], 3, 3)
    line([(394, 312), (442, 301), (489, 300)], 9, 2)
    for x, y, h in [(272, 222, 32), (304, 226, 41), (381, 190, 27), (403, 190, 42)]:
        line([(x, y+4), (x, y-h)], 6, 3)
        for offset, half in [(0, 8), (10, 11), (20, 14)]:
            top = y-h+offset
            polygon([(x, top-8), (x-half, top+6), (x+half, top+6)], 6)


