def foreground(p, rng):
    for ink, ridge, count, low, high in (
        (1, [(0, 385), (64, 367), (123, 382), (163, 401), (230, 447)], 16, 9, 26),
        (0, [(0, 424), (65, 401), (104, 407), (153, 431), (208, 469)], 12, 20, 50),
        (1, [(499, 451), (550, 410), (598, 389), (639.7, 377)], 12, 10, 30),
        (0, [(518, 479), (557, 454), (604, 422), (639.7, 419)], 10, 23, 60),
    ):
        p.polygon(ink, *ridge, (ridge[-1][0], 480), (ridge[0][0], 480))
        for index in range(count):
            x = ridge[0][0] + (ridge[-1][0] - ridge[0][0]) * (
                index + rng.uniform(.15, .85)) / count
            a, b = next((a, b) for a, b in zip(ridge, ridge[1:]) if a[0] <= x <= b[0])
            y = a[1] + (b[1] - a[1]) * (x - a[0]) / (b[0] - a[0]) + 4
            height = rng.randint(low, high)
            width = height * rng.uniform(.19, .28)
            lean = rng.uniform(-.14, .14)
            outline = [(-.15, 0), (-1, .12), (-.47, .36), (-.8, .3),
                       (-.31, .56), (-.55, .51), (-.2, .73),
                       (0, 1), (.32, .7), (.52, .52), (.26, .59),
                       (.78, .35), (.49, .4), (1, .13), (.14, 0)]
            p.polygon(ink, *((max(0, min(639.7, x + width * (u + lean * v))),
                              y - height * v) for u, v in outline))
            if ink == 0 and height >= 36:
                side = 1 if x < 320 else -1
                p.polygon(1, (x + side * width * .28, y - height * .17),
                          (x + side * width * .56, y - height * .22),
                          (x + width * lean, y - height * .84),
                          (x + side * width * .21, y - height * .38))


