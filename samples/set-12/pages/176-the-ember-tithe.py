def coordinate(x, y):
    """Pack design-space deltas as signed four-byte NAPLPS coordinates."""
    x = round(x * 2048 / 640)
    y = round(-y * 2048 / 614.4)
    return bytes(0x40 | ((x >> shift) & 7) << 3 | ((y >> shift) & 7)
                 for shift in (9, 6, 3, 0))


def absolute(x, y):
    return coordinate(x, y - 480)


class Picture:
    def __init__(self):
        self.data = bytearray(SETUP)
        self.ink = None
        for index, colour in enumerate(PALETTE):
            r, g, b = bytes.fromhex(colour)
            self.select(index)
            self.command(0x3c, bytes(
                0x40 | ((g >> s) & 2) << 4 | ((r >> s) & 2) << 3 | ((b >> s) & 2) << 2
                | ((g >> s) & 1) << 2 | ((r >> s) & 1) << 1 | ((b >> s) & 1)
                for s in (6, 4, 2, 0)
            ))

    def command(self, opcode, data):
        self.data.append(opcode)
        self.data.extend(data)

    def select(self, ink):
        if self.ink != ink:
            self.command(0x3e, bytes([0x40 + 4 * ink]))
            self.ink = ink

    def polygon(self, ink, *points):
        self.select(ink)
        relative = (coordinate(x2 - x1, y2 - y1)
                    for (x1, y1), (x2, y2) in zip(points, points[1:]))
        self.command(0x37, absolute(*points[0]) + b''.join(relative))

    def disc(self, ink, x, y, radius):
        self.select(ink)
        self.command(0x2f, absolute(x - radius, y) + coordinate(2 * radius, 0))

    def lines(self, ink, *points):
        self.select(ink)
        self.command(0x2a, b''.join(absolute(*point) for point in points))

    def points(self, ink, points):
        self.select(ink)
        self.command(0x26, b''.join(absolute(*point) for point in points))


