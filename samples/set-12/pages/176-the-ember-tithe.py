def soften_bends(points):
    """Round interior corners while keeping the river open at the frame edge."""
    for _ in range(2):
        rounded = []
        for index, (x, y) in enumerate(points):
            if y == 480:
                rounded.append((x, y))
                continue
            for px, py in (points[index - 1], points[(index + 1) % len(points)]):
                rounded.append((.76 * x + .24 * px, .76 * y + .24 * py))
        points = rounded
    return points


